{
    for (const auto& c : cases) {
        SCOPED_TRACE(c.name);
        CostModelInput input{.op = c.op, .dtype = c.dtype, .rows = c.r, .cols = c.c, .arch = CostModelArch::A5};
        auto& g = input.default_input;
        g.present = true;
        g.enabled = true;
        g.supported_layout = true;
        g.runtime_valid_shape = true;
        g.profile = c.profile;
        g.index_dtype = c.index_dtype;
        g.dst = {c.r, c.c, c.r, c.c, c.c, true, c.dst_base};
        g.src = {c.sr, c.sc, c.sr, c.sc, c.sc, true, c.src_base};
        g.index = {c.r, c.ic, c.r, c.op == PtoOpcode::TGATHERB ? c.ic : c.c, c.ic, true, 0};
        CostModelResult result;
        ASSERT_TRUE(EstimateCycles(input, result));
        EXPECT_EQ(result.assumed_input_profile, c.profile);
        EXPECT_LE(std::abs(result.cycles - c.measured) / c.measured, 0.10);
    }
}
