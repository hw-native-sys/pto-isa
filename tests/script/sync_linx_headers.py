        if name == "TSEL":
            call = "select(dst, mask, true_src, dst)"
        if name == "TSELS":
            call = "selectScalar(dst, src0, src1, s)"
        if name == "TPREFETCH":
            call = "prefetch(src, valid_col, valid_row)"
        if name == "TGATHER":
            call = "gather(dst, src, off)"
        if name == "TSCATTER":
            call = "scatter(dst, src, off)"
        if name in ["MGATHER", "MGATHER_MASK"]:
            maskArg = "mask" if name.endswith("_MASK") else "noOperand"
            rangeArg = "range" if "IndexedByteRange" in sig else "unboundedRange"
            call = f"memoryGather<static_cast<int>(Pad)>(dst, src, offset, {maskArg}, {rangeArg})"
        if name in ["MSCATTER", "MSCATTER_MASK"]:
            maskArg = "mask" if name.endswith("_MASK") else "noOperand"
